"""MITRE ATT&CK mapping with transparent rules, and official mitigations from the local ATT&CK STIX bundle.

Techniques come from explicit, explainable rules over (vulnerability text, asset role/zone, observed telemetry).
Mitigations come only from ATT&CK's own `mitigates` relationships, so every recommended control carries a real
M-ID. Nothing here is generated by a language model.
"""

from __future__ import annotations

import functools
import json
import re
from pathlib import Path

STIX = Path(__file__).resolve().parents[3] / "data" / "raw" / "enterprise-attack.json"

# (technique id, condition description, predicate over the context dict)
RULES: list[tuple[str, str, callable]] = [
    ("T1190", "network-reachable flaw on an internet-facing or DMZ asset",
     lambda c: c["network"] and c["zone"] in {"internet", "dmz"}),
    ("T1133", "remote-access gateway (VPN / remote support) is the target",
     lambda c: c["role"] in {"vpn", "remote-admin"}),
    ("T1068", "vulnerability grants privilege escalation",
     lambda c: re.search(r"privilege[s]? (escalation|to root)|escalat\w+ privileges|gain (root|system)", c["text"], re.I)),
    ("T1078", "authentication bypass yields valid-session access",
     lambda c: re.search(r"authentication bypass|bypass(es)? authentication|missing authentication", c["text"], re.I)),
    ("T1059", "arbitrary command / code execution",
     lambda c: re.search(r"arbitrary (command|code)|command injection|remote code execution|execute (arbitrary )?commands",
                         c["text"], re.I)),
    ("T1505.003", "web-facing appliance commonly backdoored with web shells after exploitation",
     lambda c: c["network"] and c["role"] in {"vpn", "web", "web-portal", "adc", "app"} and c["exploited"]),
    ("T1210", "flaw in a service reachable from inside the network (lateral movement)",
     lambda c: c["network"] and c["zone"] == "internal"),
    ("T1499", "denial of service", lambda c: re.search(r"denial of service|\bDoS\b|reload unexpectedly|crash", c["text"], re.I)),
    ("T1595.002", "vulnerability scanning observed on the national decoy grid", lambda c: c["decoy_surge"]),
    ("T1071.001", "periodic C2 beacon over web protocols seen in firewall logs", lambda c: c["beacon"]),
    ("T1566.002", "phishing link delivery", lambda c: re.search(r"phishing|lookalike domain|sms messages with links", c["text"], re.I)),
]
MITIGATION_PRIORITY = ["M1051", "M1035", "M1030", "M1026", "M1032", "M1042", "M1050", "M1048", "M1016", "M1031", "M1037",
                       "M1021", "M1017", "M1018"]


def _ext(o: dict) -> str | None:
    return next((r["external_id"] for r in o.get("external_references", []) if r.get("source_name") == "mitre-attack"),
                None)


@functools.lru_cache(maxsize=1)
def _catalog() -> tuple[dict, dict, dict]:
    objs = json.loads(STIX.read_text(encoding="utf-8"))["objects"]
    techniques = {o["id"]: o for o in objs if o["type"] == "attack-pattern" and not o.get("revoked")
                  and not o.get("x_mitre_deprecated")}
    mitigations = {o["id"]: o for o in objs if o["type"] == "course-of-action" and not o.get("revoked")
                   and not o.get("x_mitre_deprecated")}
    by_tid = {_ext(o): o for o in techniques.values()}
    mitigates: dict[str, list[str]] = {}
    for o in objs:
        if o["type"] == "relationship" and o["relationship_type"] == "mitigates" and o["target_ref"] in techniques \
                and o["source_ref"] in mitigations:
            mitigates.setdefault(_ext(techniques[o["target_ref"]]), []).append(_ext(mitigations[o["source_ref"]]))
    m_by_id = {_ext(o): o for o in mitigations.values()}
    return by_tid, mitigates, m_by_id


def map_alert(text: str, asset: dict, cvss_vector: str | None, exploited: bool, decoy_surge: bool,
              beacon: bool) -> dict:
    by_tid, mitigates, m_by_id = _catalog()
    ctx = {"text": text or "", "zone": asset.get("zone"), "role": asset.get("role"),
           "network": (cvss_vector or "AV:N").find("AV:N") >= 0, "exploited": exploited,
           "decoy_surge": decoy_surge, "beacon": beacon}
    techniques = []
    for tid, why, pred in RULES:
        if pred(ctx) and tid in by_tid:
            o = by_tid[tid]
            techniques.append({"id": tid, "name": o["name"], "why": why,
                               "tactics": [p["phase_name"] for p in o.get("kill_chain_phases", [])],
                               "url": f"https://attack.mitre.org/techniques/{tid.replace('.', '/')}/"})
    counts: dict[str, int] = {}
    for t in techniques:
        for m in mitigates.get(t["id"], []):
            counts[m] = counts.get(m, 0) + 1
    ranked = sorted(counts, key=lambda m: (MITIGATION_PRIORITY.index(m) if m in MITIGATION_PRIORITY else 99, -counts[m]))
    mitigations = [{"id": m, "name": m_by_id[m]["name"], "covers": counts[m],
                    "description": re.sub(r"\(Citation:[^)]*\)", "", m_by_id[m].get("description", "")).strip()[:220],
                    "url": f"https://attack.mitre.org/mitigations/{m}/"} for m in ranked[:5] if m in m_by_id]
    return {"techniques": techniques, "mitigations": mitigations, "source": "MITRE ATT&CK Enterprise (local STIX snapshot)"}
